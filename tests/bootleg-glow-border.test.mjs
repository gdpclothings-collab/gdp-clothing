import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import {
  DEFAULT_PHOTO_BORDER, PHOTO_BORDER_STYLES,
  normalizePhotoBorder, hasPhotoBorder, createPhotoBorderImage,
} from '../src/lib/customStudioV2PhotoBorders.js';

const editor = readFileSync('src/components/storefront/custom-studio-v2/ProtectedTemplateEditorV2.jsx', 'utf8');
const production = readFileSync('src/lib/customStudioV2ProtectedProduction.js', 'utf8');
const admin = readFileSync('src/pages/TemplateManager.jsx', 'utf8');
const checkout = readFileSync('src/pages/CustomStudioV2.jsx', 'utf8');

test('Bootleg Glow is opt-in; existing designs and other border presets retain their behavior', () => {
  assert.equal(DEFAULT_PHOTO_BORDER.style, 'none');
  assert.deepEqual(PHOTO_BORDER_STYLES.map((x) => x.id), ['none', 'outline', 'glow', 'rough', 'bootlegGlow']);
  assert.equal(hasPhotoBorder({ style: 'bootlegGlow', innerThickness: 0, glowSize: 0 }), false);
  assert.equal(hasPhotoBorder({ style: 'bootlegGlow', innerThickness: 0, glowOpacity: 0 }), false);
  assert.equal(hasPhotoBorder({ style: 'bootlegGlow', innerThickness: 0, glowOpacity: 80 }), true);
  assert.equal(hasPhotoBorder({ style: 'bootlegGlow', innerThickness: 40, glowOpacity: 0 }), true);
  assert.equal(hasPhotoBorder({ style: 'bootlegGlow', opacity: 0 }), false);
  assert.equal(hasPhotoBorder({ style: 'glow', thickness: 0 }), false);
  assert.equal(hasPhotoBorder({ style: 'rough', opacity: 0 }), false);
  assert.equal(createPhotoBorderImage({}, 800, 800, {}), null);
});

test('Photo Glow fields have stable printable defaults and sanitized bounded inputs', () => {
  const defaults = normalizePhotoBorder({ style: 'bootlegGlow' });
  assert.equal(defaults.innerColor, '#ffffff');
  assert.equal(defaults.glowColor, '#ee4dff');
  assert.ok(defaults.innerThickness > 0 && defaults.glowSize > 0 && defaults.feather > 0);
  const safe = normalizePhotoBorder({
    style: 'bootlegGlow',
    innerColor: 'url(exploit)',
    glowColor: 'javascript:evil',
    innerThickness: 900,
    glowSize: -40,
    glowOpacity: 10000,
    feather: NaN,
    roughness: 900,
  });
  assert.equal(safe.innerColor, DEFAULT_PHOTO_BORDER.innerColor);
  assert.equal(safe.glowColor, DEFAULT_PHOTO_BORDER.glowColor);
  assert.deepEqual([safe.innerThickness, safe.glowSize, safe.glowOpacity, safe.feather, safe.roughness], [100, 0, 100, 0, 100]);
});

test('Glow is composed in three alpha-only layers; source photo always stays sharp', () => {
  const created = [];
  const originalDocument = globalThis.document;
  globalThis.document = {
    createElement(tag) {
      assert.equal(tag, 'canvas');
      const operations = [];
      const context = {
        operations,
        globalAlpha: 1,
        globalCompositeOperation: 'source-over',
        filter: 'none',
        drawImage(...args) { operations.push(['drawImage', ...args]); },
        fillRect(...args) { operations.push(['fillRect', ...args]); },
      };
      const canvas = { width: 0, height: 0, getContext: () => context };
      created.push({ canvas, context });
      return canvas;
    },
  };
  try {
    const photo = { source: 'cutout-alpha' };
    const built = createPhotoBorderImage(photo, 600, 900, {
      style: 'bootlegGlow',
      innerColor: '#ffffff',
      glowColor: '#dd30ff',
      innerThickness: 35,
      glowSize: 68,
      glowOpacity: 87,
      feather: 75,
      roughness: 20,
    });
    assert.ok(built);
    assert.equal(created.length, 4, 'one composite, one spread mask, one blurred/tinted mask and one inner rim');
    assert.equal(built.canvas, created[0].canvas);
    assert.ok(built.leftPad > 0 && built.topPad > 0);
    assert.ok(built.widthScale > 1 && built.heightScale > 1);
    const [composite, spread, blurred, inner] = created.map((x) => x.context);
    assert.ok(spread.operations.some((op) => op[0] === 'drawImage' && op[1] === photo), 'halo spread is derived from photo alpha');
    assert.ok(blurred.operations.some((op) => op[0] === 'drawImage' && op[1] === created[1].canvas), 'glow is generated by blurring the halo mask');
    assert.ok(blurred.operations.some((op) => op[0] === 'fillRect') && blurred.globalCompositeOperation === 'source-over', 'halo is colorized');
    assert.ok(inner.operations.some((op) => op[0] === 'drawImage' && op[1] === photo), 'rim uses photo alpha for interior subtraction');
    assert.ok(inner.operations.some((op) => op[0] === 'fillRect'), 'white rim is colorized separately');
    assert.deepEqual(composite.operations.filter((op) => op[0] === 'drawImage').map((op) => op[1]), [created[2].canvas, created[3].canvas]);
    assert.ok(!composite.operations.some((op) => op[1] === photo), 'original photograph is not blurred into the effect');
    assert.equal(built.opacity, 1);
  } finally {
    globalThis.document = originalDocument;
  }
});

test('Cutout effect shares the protected production render path with preview and maintains print-area cropping', () => {
  assert.match(production, /createPhotoBorderImage\(loaded\.image, loaded\.width, loaded\.height, layer\.border\)/);
  assert.match(production, /paint\(output\.context, preparedBorder, 'both'\)/);
  assert.match(production, /paint\(borderOutput\.context, preparedBorder, 'borderOnly'\)/);
  assert.match(production, /if \(returnDesignCanvas\)/);
  assert.match(editor, /data-gdp-bootleg-cutout-borders="true"/);
  assert.match(editor, /paintPhotoBorders\(rendered\.borderCanvas\)/);
  assert.match(editor, /overflow-hidden rounded-lg border border-dashed/);
  assert.match(production, /globalCompositeOperation = 'source-atop'/);
  assert.match(checkout, /border: layer\.border \|\| \{ style: 'none' \}/);
});

test('Glow controls affect the selected photo only and are admin-toggleable', () => {
  assert.match(editor, /data-gdp-bootleg-glow-controls="true"/);
  for (const name of ['innerColor', 'innerThickness', 'glowColor', 'glowSize', 'glowOpacity', 'feather', 'roughness']) {
    assert.match(editor, new RegExp('updateActivePhotoBorder\\(\\{ ' + name + ':'));
    assert.match(editor, new RegExp('activePhotoBorder\\.' + name));
  }
  assert.match(editor, /layer\.id === activePhoto\.id \? \{ \.\.\.layer, border: normalized \} : layer/);
  assert.match(admin, /data-gdp-admin-bootleg-glow="true"/);
  assert.match(admin, /enabledBorderStyles\.includes\(style\.id\)/);
  assert.match(admin, /saveCustomStudioSettings\(settings\)/);
  assert.match(editor, /settings\.photoBorderOptions\.enabledStyles\.includes\(preset\.id\)/);
});
